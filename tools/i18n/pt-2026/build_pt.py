# -*- coding: utf-8 -*-
"""
Build Portuguese article pages from the English page plus a gated translation.

    python tools/i18n/pt-2026/build_pt.py <site-root> <content-dir> [slug ...]

The page is the ENGLISH page, edited in place: every stylesheet, sprite and
layout block stays byte-identical, and only these change --

  head     <html lang>, title, description, canonical, og/twitter strings,
           og:locale, the Article node of the JSON-LD and the breadcrumbs
  links    the alternates block and the switcher, generated by langlinks.rewrite()
           -- the same code that maintains every other page
  chrome   header and footer text, and the five chrome links that have a
           Portuguese page (product, solutions, resources, about, contact).
           Pricing, the brand mark, privacy and terms stay English, by decision.
  wrap     back link, article head, main, rail, CTA, hero alt; every relative
           URL made root-absolute (href, src, srcset, imagesrcset, poster --
           README "the path trap")

Every replacement is asserted to fire the expected number of times, and the
chrome is checked as a SET afterwards: every text node left in the header and
footer must be Portuguese or on a short allowlist, so a label nobody put in the
map fails the build instead of shipping English. See README, "An enumeration
of names that looked complete".

The postflight is verify_pt.py, which runs over the whole document.
"""

import glob, html, io, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
I18N = os.path.dirname(HERE)
sys.path.insert(0, I18N)
import gate
import langlinks

SITE = "https://amazebase.pro"
LANG = "pt"
ARTICLES = "pt/artigos"
TOP = {"resources": "pt/recursos.html", "product": "pt/produto.html",
       "solutions": "pt/solucoes.html", "about": "pt/sobre.html",
       "contact": "pt/contato.html"}
# The manifest entry langlinks will get when all 51 exist. Until then it is
# used only to generate these pages' own alternates and switcher.
PT_ENTRY = {"code": "pt", "label": u"Português", "chip": "PT",
            "articles": ARTICLES, "top": TOP}

CHROME_HREF = {"/product.html": "/pt/produto.html", "/solutions.html": "/pt/solucoes.html",
               "/resources.html": "/pt/recursos.html", "/about.html": "/pt/sobre.html",
               "/contact.html": "/pt/contato.html"}

